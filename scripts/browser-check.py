def capture_console(kind, msg):
    if msg.type != 'error':
        return
    if '409' in msg.text and '/switch' in msg.location.get('url', ''):
        expected_http_errors.append(kind + ': ' + msg.text + '（已死人物场景切换，预期拒绝）')
    else:
        errors.append(kind + ' console: ' + msg.text)

def check(name, value, detail=''):
    results.append({'name': name, 'passed': bool(value), 'detail': detail})
    if not value:
        raise AssertionError(f'{name}: {detail}')

def overflow(page):
    return page.evaluate('document.documentElement.scrollWidth > innerWidth + 1')

def send(page, text):
    page.locator('#chat-input').fill(text)
    page.locator('#send-message').click()
    page.locator('#stop-message').wait_for(state='visible')
    page.locator('#stop-message').wait_for(state='hidden', timeout=20000)
    page.wait_for_timeout(150)
    check('消息完成且输入清空', page.locator('#chat-input').input_value() == '', page.locator('#chat-error').inner_text() if page.locator('#chat-error').is_visible() else '')

def session_id(page, chapter):
    return page.evaluate('(id) => JSON.parse(localStorage.getItem("rushi:session:" + id))', chapter)

def session_data(page, sid):
    return page.evaluate('(id) => fetch("/api/sessions/" + id).then(r => r.json())', sid)

